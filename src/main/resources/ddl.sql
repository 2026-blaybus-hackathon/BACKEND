CREATE TABLE users
(
    id               NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    updated_datetime TIMESTAMP NOT NULL,
    created_datetime TIMESTAMP NOT NULL,
    email            VARCHAR2(100)                                  NOT NULL,
    password         VARCHAR2(255)                                  NOT NULL,
    name             VARCHAR2(100)                                  NOT NULL,
    nickname         VARCHAR2(100)                                  NOT NULL,
    role             VARCHAR2(20)                                   NOT NULL,
    profile_name     VARCHAR2(100),
    origin_file_name VARCHAR2(255),
    mentor_id NUMBER(38, 0),
    CONSTRAINT pk_users PRIMARY KEY (id)
);

ALTER TABLE users
    ADD CONSTRAINT uc_users_email UNIQUE (email);

CREATE INDEX idx_users_nickname ON users (nickname);

ALTER TABLE users
    ADD CONSTRAINT FK_USERS_ON_MENTOR FOREIGN KEY (mentor_id) REFERENCES users (id);

CREATE INDEX idx_users_mentor_id ON users (mentor_id);

CREATE TABLE daily_planners
(
    id               NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    updated_datetime TIMESTAMP                                      NOT NULL,
    created_datetime TIMESTAMP                                      NOT NULL,
    user_id          NUMBER(38, 0)                                  NOT NULL,
    "DATE"           date                                           NOT NULL,
    total_feedback   VARCHAR2(255),
    CONSTRAINT pk_daily_planners PRIMARY KEY (id)
);

CREATE INDEX idx_daily_planners_date ON daily_planners ("DATE");

ALTER TABLE daily_planners
    ADD CONSTRAINT FK_DAILY_PLANNERS_ON_USER FOREIGN KEY (user_id) REFERENCES users (id);

CREATE INDEX idx_daily_planners_user_id ON daily_planners (user_id);

CREATE TABLE tasks
(
    id                        NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    updated_datetime          TIMESTAMP                                      NOT NULL,
    created_datetime          TIMESTAMP                                      NOT NULL,
    daily_planner_id          NUMBER(38, 0)                                  NOT NULL,
    subject                   VARCHAR2(20)                                   NOT NULL,
    title                     VARCHAR2(255)                                  NOT NULL,
    content                   CLOB,
    "COMMENT"                 VARCHAR2(1023),
    user_id                   NUMBER(38, 0)                                  NOT NULL,
    study_duration_in_minutes INTEGER,
    is_completed              NUMBER(1)                                      NOT NULL,
    CONSTRAINT pk_tasks PRIMARY KEY (id)
);

CREATE INDEX idx_tasks_subject ON tasks (subject);

ALTER TABLE tasks
